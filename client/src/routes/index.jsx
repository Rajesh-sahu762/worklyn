import { Navigate, Route, Routes } from "react-router";
import ProtectedRoute from "./ProtectedRoute";
import PublicOnlyRoute from "./PublicOnlyRoute";
import LoginPage from "../pages/LoginPage";
import RegisterPage from "../pages/RegisterPage";
import HomePage from "../pages/HomePage";
import CreateOrganizationPage from "../pages/CreateOrganizationPage";
import ProjectsPage from "../pages/ProjectsPage";
import AppShell from "../components/layout/AppShell";
import ProjectOverviewPage from "../pages/ProjectOverviewPage";
import ProjectIssuesPage from "../pages/ProjectIssuesPage";
import ProjectBacklogPage from "../pages/ProjectBacklogPage";
import ProjectMembersPage from "../pages/ProjectMembersPage";
import ProjectSettingsPage from "../pages/ProjectSettingsPage";
import IssueDetailPage from "../pages/IssueDetailPage";
import OrganizationMembersPage from "../pages/OrganizationMembersPage";
import OrganizationSettingsPage from "../pages/OrganizationSettingsPage";
import AcceptInvitationPage from "../pages/AcceptInvitationPage";

// Single place for the route table. As the app grows, split into
// organizationRoutes.jsx, teamRoutes.jsx, ... and mount them here.
export default function AppRoutes() {
  return (
    <Routes>
      <Route element={<PublicOnlyRoute />}>
        <Route path="/login" element={<LoginPage />} />
        <Route path="/register" element={<RegisterPage />} />
      </Route>

      <Route element={<ProtectedRoute />}>
        <Route element={<AppShell />}>
          <Route path="/" element={<HomePage />} />
          <Route
            path="/organizations/new"
            element={<CreateOrganizationPage />}
          />
          <Route path="/projects" element={<ProjectsPage />} />
          <Route
            path="/projects/:projectId"
            element={<ProjectOverviewPage />}
          />
          <Route path="/projects/:projectId/backlog" element={<ProjectBacklogPage />} />
          <Route path="/projects/:projectId/members" element={<ProjectMembersPage />} />
          <Route path="/projects/:projectId/settings" element={<ProjectSettingsPage />} />
          <Route
            path="/projects/:projectId/issues"
            element={<ProjectIssuesPage />}
          />
          <Route
            path="/projects/:projectId/issues/:issueId"
            element={<IssueDetailPage />}
          />
          <Route path="/members" element={<OrganizationMembersPage />} />
          <Route path="/settings/organization" element={<OrganizationSettingsPage />} />
          <Route
            path="/invitations/accept"
            element={<AcceptInvitationPage />}
          />
          {/* Backwards-compatible path used by invitation links generated by the API. */}
          <Route
            path="/accept-invitation"
            element={<AcceptInvitationPage />}
          />
          <Route
            path="/invitations/:token"
            element={<AcceptInvitationPage />}
          />
        </Route>
      </Route>

      <Route path="*" element={<Navigate to="/" replace />} />
    </Routes>
  );
}
